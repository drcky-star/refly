const RTL_LANGS = ["ar"];

function reflyLang() { return localStorage.getItem("refly_lang") || "en"; }  // varsayılan: İngilizce

function t(key, ...args) {
  const lang = reflyLang();
  let s = (lang !== "tr" && I18N[lang] && I18N[lang][key] != null) ? I18N[lang][key] : key;
  args.forEach((a, i) => { s = s.replaceAll("{" + i + "}", a); });
  return s;
}

function setLang(lang) {
  localStorage.setItem("refly_lang", lang);
  document.cookie = "lang=" + lang + ";path=/;max-age=31536000";
  applyDir();
  location.reload();   // en temizi: sayfayı yeni dille yeniden çiz
}

function applyDir() {
  const rtl = RTL_LANGS.includes(reflyLang());
  document.documentElement.dir = rtl ? "rtl" : "ltr";
  document.documentElement.lang = reflyLang();
}

// statik [data-i18n] öğelerini ve placeholder'ları çevir
function applyStatic() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
}

